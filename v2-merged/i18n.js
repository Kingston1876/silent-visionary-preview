  function getSavedLang() {
    try {
      var saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved && translations[saved]) return saved;
    } catch (e) {}
    return DEFAULT_LANG;
  }

  function applyLanguage(lang) {
    var dict = translations[lang] || translations[DEFAULT_LANG];
    var fallback = translations[DEFAULT_LANG];
    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute("data-i18n");
      var value = dict[key] || fallback[key];
      if (value !== undefined) {
        nodes[i].innerHTML = value;
      }
    }
    var placeholderNodes = document.querySelectorAll("[data-i18n-placeholder]");
    for (var j = 0; j < placeholderNodes.length; j++) {
      var pKey = placeholderNodes[j].getAttribute("data-i18n-placeholder");
      var pValue = dict[pKey] || fallback[pKey];
      if (pValue !== undefined) {
        placeholderNodes[j].setAttribute("placeholder", pValue);
      }
    }
    document.documentElement.setAttribute("lang", lang);
    var select = document.getElementById("lang-select");
    if (select) select.value = lang;
  }

  function setLanguage(lang) {
    if (!translations[lang]) lang = DEFAULT_LANG;
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    applyLanguage(lang);
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLanguage(getSavedLang());
    var select = document.getElementById("lang-select");
    if (select) {
      select.addEventListener("change", function () {
        setLanguage(select.value);
      });
    }
  });
